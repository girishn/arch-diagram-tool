// Writes schema/diagram-spec.v1.schema.json (JSON Schema 2020-12) for editors: `node scripts/gen-schema.ts`.
// The enum lists come from src/schema.ts and the property names from the validator's KNOWN table, so the schema cannot drift from them;
// a unit test also regenerates it and fails if the committed file is stale. The schema is for editor squiggles and completion:
// the validator in src/validate.ts is the authority (it also checks things a schema cannot, like links pointing at real nodes).
import { mkdirSync, writeFileSync } from "node:fs";
import { INTERACTIONS, LEVELS, PATTERNS, PLANES, TRAFFIC, ZONE_KINDS } from "../src/schema.ts";
import { KNOWN } from "../src/validate.ts";

type Json = Record<string, unknown>;
const str = (extra: Json = {}): Json => ({ type: "string", minLength: 1, ...extra });
const ref = (name: string): Json => ({ $ref: `#/$defs/${name}` });
const arr = (items: Json, extra: Json = {}): Json => ({ type: "array", items, ...extra });
const point: Json = { type: "array", prefixItems: [{ type: "number" }, { type: "number" }], items: false, minItems: 2 };

/** An object with the given properties; `x-` fields are always allowed, anything else is flagged. */
function obj(part: keyof typeof KNOWN, defs: Record<string, Json>, required: string[]): Json {
  const missing = KNOWN[part]!.filter((k) => !(k in defs));
  const extra = Object.keys(defs).filter((k) => !KNOWN[part]!.includes(k));
  if (missing.length || extra.length) throw new Error(`schema for "${part}" is out of step with the validator: missing ${missing.join(", ") || "none"}, unexpected ${extra.join(", ") || "none"}`);
  return { type: "object", properties: defs, required, patternProperties: { "^x-": {} }, additionalProperties: false };
}

const meta = {
  tags: arr(str()),
  properties: { type: "object", additionalProperties: { type: ["string", "number", "boolean"] } },
  references: arr(ref("reference")),
  source: ref("source"),
};

const lensFacts: Json = { type: "object", additionalProperties: ref("lensFact") };

const schema = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  $id: "https://example.invalid/arch-diagram-tool/diagram-spec.v1.schema.json",
  title: "Architecture diagram spec, version 1",
  description: "Generated by scripts/gen-schema.ts. The validator in src/validate.ts is the authority; this schema is for editors.",
  ...obj(
    "spec",
    {
      $schema: { type: "string" },
      version: { const: 1 },
      title: str(),
      description: { type: "string" },
      nodes: arr(ref("node"), { minItems: 1 }),
      links: arr(ref("link")),
      layers: arr(obj("layer", { id: str(), label: str(), summary: { type: "string" } }, ["id", "label"])),
      zones: arr(ref("zone")),
      trace: arr(obj("step", { node: str(), label: str() }, ["node", "label"])),
      prose: arr({ type: "object", properties: { id: str(), text: str(), mentions: arr(str()) }, required: ["id", "text", "mentions"] }),
      lenses: arr({ type: "object", properties: { id: str(), label: str(), summary: { type: "string" } }, required: ["id"], additionalProperties: false }),
      lintIgnore: arr(ref("lintIgnore")),
    },
    ["version", "title", "nodes", "links"],
  ),
  $defs: {
    reference: { type: "object", properties: { label: str(), url: str({ pattern: "^(https?://|mailto:|\\.{0,2}/(?!/)|#)" }) }, required: ["label", "url"], additionalProperties: false },
    source: { type: "object", properties: { address: str(), file: str(), line: { type: "integer", minimum: 1 } }, additionalProperties: false },
    lensFact: { type: "object", properties: { level: { enum: [...LEVELS] }, badge: str(), text: { type: "string" } }, required: ["badge"], patternProperties: { "^x-": {} }, additionalProperties: false },
    lintIgnore: { type: "object", properties: { rule: str(), path: str(), reason: str() }, required: ["rule", "reason"], additionalProperties: false },
    node: obj(
      "node",
      {
        id: str(),
        label: str(),
        sub: { type: "string" },
        at: { type: "object", properties: { col: { type: "number" }, row: { type: "number" } }, required: ["col", "row"], additionalProperties: false },
        icons: arr({ oneOf: [str(), { type: "object", properties: { icon: str(), label: str() }, required: ["icon", "label"], additionalProperties: false }] }, { minItems: 1 }),
        layer: str(),
        plane: { enum: [...PLANES] },
        peripheral: { type: "boolean" },
        scale: obj("scale", { min: { type: "number", minimum: 0 }, max: { type: "number", minimum: 0 }, unit: { type: "string" }, trigger: { type: "string" } }, ["min", "max"]),
        detail: obj("detail", { tag: { type: "string" }, role: { type: "string" }, why: { type: "string" }, tradeoff: { type: "string" }, mentions: arr(str()) }, []),
        lenses: lensFacts,
        ...meta,
      },
      ["id", "label", "at", "icons"],
    ),
    link: obj(
      "link",
      {
        id: str({ pattern: "^[A-Za-z][\\w.-]*$" }),
        plane: { enum: [...PLANES] },
        from: str(),
        to: str(),
        label: str(),
        detail: { type: "string" },
        mentions: arr(str()),
        via: arr(point),
        offPath: { type: "boolean" },
        pattern: { enum: [...PATTERNS] },
        interaction: { enum: [...INTERACTIONS] },
        traffic: { enum: [...TRAFFIC] },
        protocol: { type: "string" },
        twoWay: { type: "boolean" },
        lenses: lensFacts,
        labelAt: point,
        ...meta,
      },
      ["from", "to", "label"],
    ),
    zone: obj(
      "zone",
      {
        id: str(),
        label: str(),
        kind: { enum: [...ZONE_KINDS] },
        members: arr(str()),
        parent: str(),
        bounds: { type: "object", properties: { c0: { type: "number" }, r0: { type: "number" }, c1: { type: "number" }, r1: { type: "number" } }, required: ["c0", "r0", "c1", "r1"], additionalProperties: false },
        ...meta,
      },
      ["id", "label"],
    ),
  },
};

export const schemaText = JSON.stringify(schema, null, 2) + "\n";

// Run directly (`node scripts/gen-schema.ts`) to write the file; importing it, as the tests do, only reads `schemaText`.
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replaceAll("\\", "/").split("/").pop()!)) {
  mkdirSync(new URL("../schema/", import.meta.url), { recursive: true });
  writeFileSync(new URL("../schema/diagram-spec.v1.schema.json", import.meta.url), schemaText);
  console.log("wrote schema/diagram-spec.v1.schema.json");
}
